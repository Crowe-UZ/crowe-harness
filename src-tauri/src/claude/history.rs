use crate::util::{is_safe_id, is_uuid, iso_time, one_line, truncate_marked};

pub const MAX_MESSAGES: usize = 1000;
pub const TOOL_INPUT_MAX: usize = 4 * 1024;
pub const TOOL_RESULT_MAX: usize = 8 * 1024;
/// Safety cap for a single text block (a pasted multi-MB log, for example).
pub const TEXT_MAX: usize = 256 * 1024;
pub const TITLE_MAX_CHARS: usize = 80;
const UNTITLED: &str = "Untitled session";
const READ_BUF: usize = 256 * 1024;

