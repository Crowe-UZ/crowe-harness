/// Cleans a user text block. Returns `None` for wrapper/meta text that is not
/// shown (command output, caveats, system reminders); slash-command wrappers
/// become `/name args`.
pub fn clean_user_text(text: &str) -> Option<String> {
    let t = text.trim();
    if t.is_empty() {
        return None;
    }
    if t.contains("<command-name>") {
        let name = between(t, "<command-name>", "</command-name>")?.trim();
        let args = between(t, "<command-args>", "</command-args>")
            .unwrap_or_default()
            .trim();
        let name = if name.starts_with('/') {
            name.to_owned()
        } else {
            format!("/{name}")
        };
        return Some(if args.is_empty() {
            name
        } else {
            format!("{name} {args}")
        });
    }
    const HIDDEN: &[&str] = &[
        "<local-command-stdout>",
        "<local-command-stderr>",
        "<local-command-caveat>",
        "<command-message>",
        "<system-reminder>",
        "Caveat: The messages below were generated by the user while running local commands",
    ];
    if HIDDEN.iter().any(|h| t.starts_with(h)) {
        return None;
    }
    Some(t.to_owned())
}

fn between<'a>(s: &'a str, open: &str, close: &str) -> Option<&'a str> {
    let start = s.find(open)? + open.len();
    let end = s[start..].find(close)? + start;
    Some(&s[start..end])
}

/// Records that are never shown: meta, compact summaries and (in a main
/// session file) sidechain records of older Claude Code versions.
fn skip_record<B>(r: &Record<B>, include_sidechain: bool) -> bool {
    r.is_meta.0 || r.is_compact_summary.0 || (!include_sidechain && r.is_sidechain.0)
}

// ---------------------------------------------------------------- summary pass

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Summary {
    pub title: String,
    pub created_at: Option<String>,
    pub updated_at: Option<String>,
    pub message_count: u32,
    pub git_branch: Option<String>,
    pub model: Option<String>,
    pub cwd: Option<String>,
}

const INTERESTING: &[&[u8]] = &[
    b"\"type\":\"user\"",
    b"\"type\":\"assistant\"",
    b"\"type\":\"custom-title\"",
    b"\"type\":\"ai-title\"",
    b"\"type\":\"summary\"",
];

fn interesting(line: &[u8]) -> bool {
    INTERESTING.iter().any(|p| memmem::find(line, p).is_some())
}

/// Calls `f` for every non-empty line of `reader` (raw bytes, no UTF-8 check).
fn for_each_line<R: BufRead>(mut reader: R, mut f: impl FnMut(&[u8])) {
    let mut buf = Vec::with_capacity(64 * 1024);
    loop {
        buf.clear();
        match reader.read_until(b'\n', &mut buf) {
            Ok(0) | Err(_) => break,
            Ok(_) => {
                let line = buf.trim_ascii();
                if !line.is_empty() {
                    f(line);
                }
            }
        }
    }
}

/// Single cheap pass over a transcript. `None` = no user/assistant message.
pub fn summarize<R: BufRead>(reader: R, include_sidechain: bool) -> Option<Summary> {
    let mut custom_title: Option<String> = None;
    let mut ai_title: Option<String> = None;
    let mut summary_title: Option<String> = None;
    let mut first_user: Option<String> = None;
    let mut created_at: Option<String> = None;
    let mut updated_at: Option<String> = None;
    let mut git_branch: Option<String> = None;
    let mut model: Option<String> = None;
    let mut cwd: Option<String> = None;
    let mut user_count = 0u32;
    let mut assistant_ids: HashSet<String> = HashSet::new();
    let mut anon_assistant = 0u32;

    for_each_line(reader, |line| {
        if !interesting(line) {
            return;
        }
        let Ok(r) = serde_json::from_slice::<Record<SummaryBlock>>(line) else {
            return;
        };
        match r.kind.get() {
            Some("custom-title") => {
                if let Some(t) = r.custom_title.non_empty() {
                    custom_title = Some(t.to_owned());
                }
            }
            Some("ai-title") => {
                if let Some(t) = r.ai_title.non_empty() {
                    ai_title = Some(t.to_owned());
                }
            }
            Some("summary") => {
                if let Some(t) = r.summary.non_empty() {
                    summary_title = Some(t.to_owned());
                }
            }
            Some(kind @ ("user" | "assistant")) => {
                if skip_record(&r, include_sidechain) {
                    return;
                }
                let Some(msg) = r.message.as_ref() else {
                    return;
                };
                let displayable = if kind == "user" {
                    match &msg.content {
                        Some(Content::Text(t)) => {
                            let cleaned = clean_user_text(t);
                            if first_user.is_none() {
                                first_user.clone_from(&cleaned);
                            }
                            cleaned.is_some()
                        }
                        Some(Content::Blocks(blocks)) => {
                            let mut any = false;
                            for b in blocks {
                                match b.kind.get() {
                                    Some("text") => {
                                        let cleaned = b.text.get().and_then(clean_user_text);
                                        if first_user.is_none() {
                                            first_user.clone_from(&cleaned);
                                        }
                                        any |= cleaned.is_some();
                                    }
                                    Some("tool_result" | "image") => any = true,
                                    _ => {}
                                }
                            }
                            any
                        }
                        None => false,
                    }
                } else {
                    let shown = match &msg.content {
                        Some(Content::Text(t)) => !t.trim().is_empty(),
                        Some(Content::Blocks(blocks)) => {
                            blocks.iter().any(|b| match b.kind.get() {
                                Some("text") => b.text.non_empty().is_some(),
                                Some("tool_use") => true,
                                _ => false,
                            })
                        }
                        None => false,
                    };
                    if let Some(m) = msg.model.non_empty().filter(|m| *m != "<synthetic>") {
                        model = Some(m.to_owned());
                    }
                    shown
                };
                if !displayable {
                    return;
                }
                if kind == "user" {
                    user_count += 1;
                } else {
                    match msg.id.non_empty() {
                        Some(id) => {
                            if !assistant_ids.contains(id) {
                                assistant_ids.insert(id.to_owned());
                            }
                        }
                        None => anon_assistant += 1,
                    }
                }
                if let Some(ts) = r.timestamp.non_empty() {
                    if created_at.is_none() {
                        created_at = Some(ts.to_owned());
                    }
                    updated_at = Some(ts.to_owned());
                }
                if let Some(b) = r.git_branch.non_empty() {
                    git_branch = Some(b.to_owned());
                }
                if let Some(c) = r.cwd.non_empty() {
                    cwd = Some(c.to_owned());
                }
            }
            _ => {}
        }
    });

    let count = user_count + assistant_ids.len() as u32 + anon_assistant;
    if count == 0 {
        return None;
    }
    let title = custom_title
        .or(ai_title)
        .or(summary_title)
        .or(first_user)
        .map(|t| one_line(&t, TITLE_MAX_CHARS))
        .filter(|t| !t.is_empty())
        .unwrap_or_else(|| UNTITLED.to_owned());
    Some(Summary {
        title,
        created_at,
        updated_at,
        message_count: count,
        git_branch,
        model,
        cwd,
    })
}

// ---------------------------------------------------------------- full pass

/// Reads a transcript into display messages (last [`MAX_MESSAGES`]).
pub fn read_messages<R: BufRead>(
    reader: R,
    include_sidechain: bool,
) -> (Vec<TranscriptMessage>, bool) {
    let mut messages: Vec<TranscriptMessage> = Vec::new();
    let mut by_api_id: HashMap<String, usize> = HashMap::new();
    let mut line_no = 0usize;

    for_each_line(reader, |line| {
        line_no += 1;
        if memmem::find(line, b"\"type\":\"user\"").is_none()
            && memmem::find(line, b"\"type\":\"assistant\"").is_none()
        {
            return;
        }
        let Ok(r) = serde_json::from_slice::<Record<FullBlock>>(line) else {
            return;
        };
        let role = match r.kind.get() {
            Some("user") => Role::User,
            Some("assistant") => Role::Assistant,
            _ => return,
        };
        if skip_record(&r, include_sidechain) {
            return;
        }
        let Some(msg) = r.message else {
            return;
        };
        let blocks = match role {
            Role::User => user_blocks(msg.content),
            Role::Assistant => assistant_blocks(msg.content),
        };
        if blocks.is_empty() {
            return;
        }
        let timestamp = r.timestamp.non_empty().map(str::to_owned);
        if role == Role::Assistant {
            let api_id = msg.id.non_empty().map(str::to_owned);
            if let Some(idx) = api_id.as_ref().and_then(|id| by_api_id.get(id)) {
                if let Some(existing) = messages.get_mut(*idx) {
                    existing.blocks.extend(blocks);
                    return;
                }
            }
            let id = api_id
                .clone()
                .or_else(|| r.uuid.non_empty().map(str::to_owned))
                .unwrap_or_else(|| format!("line-{line_no}"));
            if let Some(api_id) = api_id {
                by_api_id.insert(api_id, messages.len());
            }
            messages.push(TranscriptMessage {
                id,
                role,
                timestamp,
                model: msg
                    .model
                    .non_empty()
                    .filter(|m| *m != "<synthetic>")
                    .map(str::to_owned),
                blocks,
            });
        } else {
            messages.push(TranscriptMessage {
                id: r
                    .uuid
                    .non_empty()
                    .map(str::to_owned)
                    .unwrap_or_else(|| format!("line-{line_no}")),
                role,
                timestamp,
                model: None,
                blocks,
            });
        }
    });

    let truncated = messages.len() > MAX_MESSAGES;
    if truncated {
        messages.drain(..messages.len() - MAX_MESSAGES);
    }
    (messages, truncated)
}

fn text_block(text: &str) -> Block {
    Block::Text {
        text: truncate_marked(text, TEXT_MAX),
    }
}

fn user_blocks(content: Option<Content<FullBlock>>) -> Vec<Block> {
    match content {
        Some(Content::Text(t)) => clean_user_text(&t)
            .map(|t| text_block(&t))
            .into_iter()
            .collect(),
        Some(Content::Blocks(blocks)) => blocks
            .into_iter()
            .filter_map(|b| match b.kind.get() {
                Some("text") => b
                    .text
                    .get()
                    .and_then(clean_user_text)
                    .map(|t| text_block(&t)),
                Some("image") => Some(text_block("[image]")),
                Some("tool_result") => Some(Block::ToolResult {
                    tool_use_id: b.tool_use_id.get().unwrap_or_default().to_owned(),
                    is_error: b.is_error.0,
                    text: truncate_marked(&tool_result_text(b.content.as_ref()), TOOL_RESULT_MAX),
                }),
                _ => None,
            })
            .collect(),
        None => Vec::new(),
    }
}

fn assistant_blocks(content: Option<Content<FullBlock>>) -> Vec<Block> {
    match content {
        Some(Content::Text(t)) if !t.trim().is_empty() => vec![text_block(&t)],
        Some(Content::Blocks(blocks)) => blocks
            .into_iter()
            .filter_map(|b| match b.kind.get() {
                Some("text") => b.text.non_empty().map(text_block),
                Some("tool_use") => Some(Block::ToolUse {
                    id: b.id.get().unwrap_or_default().to_owned(),
                    name: b.name.get().unwrap_or_default().to_owned(),
                    input: truncate_marked(
                        b.input.as_ref().map_or("{}", |r| r.get()),
                        TOOL_INPUT_MAX,
                    ),
                }),
                _ => None, // thinking, redacted_thinking, server tool blocks
            })
            .collect(),
        _ => Vec::new(),
    }
}

// ---------------------------------------------------------------- files + cache

#[derive(Debug, Clone)]
pub struct FileMeta {
    pub path: PathBuf,
    pub len: u64,
    pub mtime: SystemTime,
}

impl FileMeta {
    pub fn of(path: PathBuf, meta: &std::fs::Metadata) -> Self {
        Self {
            path,
            len: meta.len(),
            mtime: meta.modified().unwrap_or(SystemTime::UNIX_EPOCH),
        }
    }
}

type CacheEntry = (u64, SystemTime, Option<Summary>);

/// Summary cache keyed by path and validated by (length, mtime).
#[derive(Default)]
pub struct HistoryCache {
    map: Mutex<HashMap<PathBuf, CacheEntry>>,
}

impl HistoryCache {
    /// `Some(summary-or-empty)` when cached and still valid.
    pub fn get(&self, f: &FileMeta) -> Option<Option<Summary>> {
        let map = self.map.lock().ok()?;
        map.get(&f.path)
            .filter(|(len, mtime, _)| *len == f.len && *mtime == f.mtime)
            .map(|(_, _, s)| s.clone())
    }

    fn put(&self, f: &FileMeta, s: Option<Summary>) {
        if let Ok(mut map) = self.map.lock() {
            map.insert(f.path.clone(), (f.len, f.mtime, s));
        }
    }

    pub fn summarize_file(
        &self,
        guard: &ConfigGuard,
        f: &FileMeta,
        sidechain: bool,
    ) -> Option<Summary> {
        if let Some(hit) = self.get(f) {
            return hit;
        }
        let summary = match guard.open(&f.path) {
            Ok(file) => summarize(BufReader::with_capacity(READ_BUF, file), sidechain),
            Err(_) => return None, // not cached: may be transient
        };
        self.put(f, summary.clone());
        summary
    }

    /// Summarizes many files in parallel (bounded worker threads).
    pub fn summarize_many(
        &self,
        guard: &ConfigGuard,
        files: &[FileMeta],
        sidechain: bool,
    ) -> Vec<Option<Summary>> {
        let results: Vec<Mutex<Option<Summary>>> = files.iter().map(|_| Mutex::new(None)).collect();
        let next = AtomicUsize::new(0);
        let workers = std::thread::available_parallelism()
            .map_or(4, |n| n.get())
            .clamp(1, 8)
            .min(files.len().max(1));
        std::thread::scope(|scope| {
            for _ in 0..workers {
                scope.spawn(|| loop {
                    let i = next.fetch_add(1, Ordering::Relaxed);
                    let Some(f) = files.get(i) else { break };
                    let s = self.summarize_file(guard, f, sidechain);
                    if let Ok(mut slot) = results[i].lock() {
                        *slot = s;
                    }
                });
            }
        });
        results
            .into_iter()
            .map(|m| m.into_inner().ok().flatten())
            .collect()
    }
}

/// Session transcript files (`<uuid>.jsonl`) of one history directory, plus
/// the names of its sub-directories (used to find subagents cheaply).
pub fn list_session_files(
    guard: &ConfigGuard,
    dir: &Path,
) -> NativeResult<(Vec<FileMeta>, HashSet<String>)> {
    let mut files = Vec::new();
    let mut subdirs = HashSet::new();
    for entry in guard.read_dir(dir)?.flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        let Ok(ft) = entry.file_type() else { continue };
        if ft.is_dir() {
            subdirs.insert(name);
        } else if ft.is_file() {
            if let Some(stem) = name.strip_suffix(".jsonl") {
                if is_uuid(stem) {
                    if let Ok(meta) = entry.metadata() {
                        files.push(FileMeta::of(entry.path(), &meta));
                    }
                }
            }
        }
    }
    Ok((files, subdirs))
}

fn session_id_of(f: &FileMeta) -> String {
    f.path
        .file_stem()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_default()
}

fn count_subagents(guard: &ConfigGuard, session_dir: &Path) -> u32 {
    let sub = session_dir.join("subagents");
    let Ok(rd) = guard.read_dir(&sub) else {
        return 0;
    };
    rd.flatten()
        .filter(|e| agent_id_of(&e.file_name().to_string_lossy()).is_some())
        .count() as u32
}

/// `agent-<id>.jsonl` -> `<id>`.
fn agent_id_of(file_name: &str) -> Option<String> {
    let id = file_name.strip_prefix("agent-")?.strip_suffix(".jsonl")?;
    is_safe_id(id).then(|| id.to_owned())
}

fn session_info(project_id: &str, f: &FileMeta, s: &Summary, subagent_count: u32) -> SessionInfo {
    let mtime = iso_time(f.mtime);
    SessionInfo {
        id: session_id_of(f),
        project_id: project_id.to_owned(),
        title: s.title.clone(),
        created_at: s.created_at.clone().unwrap_or_else(|| mtime.clone()),
        updated_at: s.updated_at.clone().unwrap_or(mtime),
        message_count: s.message_count,
        git_branch: s.git_branch.clone(),
        model: s.model.clone(),
        subagent_count,
    }
}

/// Sessions of the given history directories, newest first.
pub fn sessions_list(
    guard: &ConfigGuard,
    cache: &HistoryCache,
    project_id: &str,
    history_dirs: &[PathBuf],
) -> NativeResult<Vec<SessionInfo>> {
    let mut out = Vec::new();
    let mut seen = HashSet::new();
    for dir in history_dirs {
        let (files, subdirs) = match list_session_files(guard, dir) {
            Ok(v) => v,
            Err(e) if e.code == "not_found" => continue,
            Err(e) => return Err(e),
        };
        let summaries = cache.summarize_many(guard, &files, false);
        for (f, s) in files.iter().zip(summaries) {
            let Some(s) = s else { continue };
            let id = session_id_of(f);
            if !seen.insert(id.clone()) {
                continue;
            }
            let subagents = if subdirs.contains(&id) {
                count_subagents(guard, &dir.join(&id))
            } else {
                0
            };
            out.push(session_info(project_id, f, &s, subagents));
        }
    }
    out.sort_by(|a, b| b.updated_at.cmp(&a.updated_at));
    Ok(out)
}

fn find_session_file(
    guard: &ConfigGuard,
    history_dirs: &[PathBuf],
    session_id: &str,
) -> NativeResult<(PathBuf, FileMeta)> {
    if !is_uuid(session_id) {
        return Err(NativeError::invalid("invalid session id"));
    }
    for dir in history_dirs {
        let path = dir.join(format!("{session_id}.jsonl"));
        if let Ok(canonical) = guard.check(&path) {
            let meta = std::fs::metadata(&canonical).map_err(|e| NativeError::io("session", &e))?;
            return Ok((dir.clone(), FileMeta::of(path, &meta)));
        }
    }
    Err(NativeError::not_found("session not found"))
}

pub fn session_read(
    guard: &ConfigGuard,
    cache: &HistoryCache,
    project_id: &str,
    history_dirs: &[PathBuf],
    session_id: &str,
) -> NativeResult<Transcript> {
    let (dir, f) = find_session_file(guard, history_dirs, session_id)?;
    let file = guard.open(&f.path)?;
    let (messages, truncated) = read_messages(BufReader::with_capacity(READ_BUF, file), false);
    let summary = cache
        .summarize_file(guard, &f, false)
        .unwrap_or_else(|| Summary {
            title: UNTITLED.to_owned(),
            created_at: None,
            updated_at: None,
            message_count: 0,
            git_branch: None,
            model: None,
            cwd: None,
        });
    let subagents = list_subagents(guard, cache, &dir.join(session_id));
    let session = session_info(project_id, &f, &summary, subagents.len() as u32);
    Ok(Transcript {
        session,
        messages,
        subagents,
        truncated,
    })
}

#[derive(Debug, Default)]
struct AgentMeta {
    agent_type: Option<String>,
    description: Option<String>,
    tool_use_id: Option<String>,
}

fn read_agent_meta(guard: &ConfigGuard, path: &Path) -> AgentMeta {
    let Ok(text) = guard.read_small(path, 64 * 1024) else {
        return AgentMeta::default();
    };
    let Ok(v) = serde_json::from_str::<Value>(&text) else {
        return AgentMeta::default();
    };
    let s = |k: &str| {
        v.get(k)
            .and_then(Value::as_str)
            .filter(|s| !s.trim().is_empty())
            .map(str::to_owned)
    };
    AgentMeta {
        agent_type: s("agentType"),
        description: s("description").map(|d| one_line(&d, 200)),
        tool_use_id: s("toolUseId"),
    }
}

fn subagent_info(
    guard: &ConfigGuard,
    cache: &HistoryCache,
    sub_dir: &Path,
    id: &str,
    f: &FileMeta,
) -> SubagentInfo {
    let meta = read_agent_meta(guard, &sub_dir.join(format!("agent-{id}.meta.json")));
    let summary = cache.summarize_file(guard, f, true);
    SubagentInfo {
        id: id.to_owned(),
        agent_type: meta.agent_type,
        description: meta.description,
        tool_use_id: meta.tool_use_id,
        message_count: summary.as_ref().map_or(0, |s| s.message_count),
        updated_at: summary
            .and_then(|s| s.updated_at)
            .unwrap_or_else(|| iso_time(f.mtime)),
    }
}

/// Subagents of a session (`<session_dir>/subagents`), oldest first.
pub fn list_subagents(
    guard: &ConfigGuard,
    cache: &HistoryCache,
    session_dir: &Path,
) -> Vec<SubagentInfo> {
    let sub_dir = session_dir.join("subagents");
    let Ok(rd) = guard.read_dir(&sub_dir) else {
        return Vec::new();
    };
    let mut items: Vec<(String, FileMeta)> = rd
        .flatten()
        .filter_map(|e| {
            let id = agent_id_of(&e.file_name().to_string_lossy())?;
            let meta = e.metadata().ok()?;
            meta.is_file().then(|| (id, FileMeta::of(e.path(), &meta)))
        })
        .collect();
    items.sort_by(|a, b| a.1.mtime.cmp(&b.1.mtime).then_with(|| a.0.cmp(&b.0)));
    items
        .iter()
        .map(|(id, f)| subagent_info(guard, cache, &sub_dir, id, f))
        .collect()
}

pub fn subagent_read(
    guard: &ConfigGuard,
    cache: &HistoryCache,
    history_dirs: &[PathBuf],
    session_id: &str,
    agent_id: &str,
) -> NativeResult<SubagentTranscript> {
    if !is_safe_id(agent_id) {
        return Err(NativeError::invalid("invalid agent id"));
    }
    let (dir, _) = find_session_file(guard, history_dirs, session_id)?;
    let sub_dir = dir.join(session_id).join("subagents");
    let path = sub_dir.join(format!("agent-{agent_id}.jsonl"));
    let canonical = guard.check(&path).map_err(|e| {
        if e.code == "not_found" {
            NativeError::not_found("subagent not found")
        } else {
            e
        }
    })?;
    let meta = std::fs::metadata(&canonical).map_err(|e| NativeError::io("subagent", &e))?;
    let f = FileMeta::of(path, &meta);
    let file = guard.open(&f.path)?;
    let (messages, truncated) = read_messages(BufReader::with_capacity(READ_BUF, file), true);
    Ok(SubagentTranscript {
        subagent: subagent_info(guard, cache, &sub_dir, agent_id, &f),
        messages,
        truncated,
    })
}

