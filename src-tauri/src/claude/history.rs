//! Claude Code history: session summaries (cached) and transcript reading.
//!
//! Layout: `<projects>/<encoded-dir>/<sessionId>.jsonl`, subagents in
//! `<projects>/<encoded-dir>/<sessionId>/subagents/agent-<id>.jsonl` with an
//! `agent-<id>.meta.json` side file. Every file is opened through the
//! [`ConfigGuard`].

