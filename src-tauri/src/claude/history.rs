        let cfg = tmp.path().join(".claude");
        let dir = write_project(&cfg);
        let guard = ConfigGuard::new(&cfg, None).expect("guard");
        let cache = HistoryCache::default();
        let dirs = vec![dir];

        let list = sessions_list(&guard, &cache, "C--work-demo", &dirs).expect("list");
        assert_eq!(list.len(), 1, "empty and non-uuid sessions are skipped");
        let s = &list[0];
        assert_eq!(s.id, S1);
        assert_eq!(s.project_id, "C--work-demo");
        assert_eq!(s.subagent_count, 1);
        assert_eq!(s.message_count, 7);
        let json = serde_json::to_value(s).expect("json");
        assert!(json.get("subagentCount").is_some() && json.get("gitBranch").is_some());

        // Cached second call returns the same.
        assert_eq!(
            sessions_list(&guard, &cache, "C--work-demo", &dirs).expect("list"),
            list
        );

        let t = session_read(&guard, &cache, "C--work-demo", &dirs, S1).expect("read");
        assert_eq!(t.messages.len(), 7);
        assert_eq!(t.subagents.len(), 1);
        let sa = &t.subagents[0];
        assert_eq!(sa.id, "a1b2c3");
        assert_eq!(sa.agent_type.as_deref(), Some("general-purpose"));
        assert_eq!(sa.description.as_deref(), Some("Explore"));
        assert_eq!(sa.tool_use_id.as_deref(), Some("toolu_2"));
        assert_eq!(sa.message_count, 2);
        assert_eq!(sa.updated_at, "2026-01-01T00:00:04.900Z");

        let st = subagent_read(&guard, &cache, &dirs, S1, "a1b2c3").expect("subagent");
        assert_eq!(st.messages.len(), 2);
        assert_eq!(st.subagent.agent_type.as_deref(), Some("general-purpose"));

        assert_eq!(
            session_read(&guard, &cache, "p", &dirs, "../../.credentials")
                .expect_err("bad id")
                .code,
            "invalid_argument"
        );
        assert_eq!(
            subagent_read(&guard, &cache, &dirs, S1, "../x")
                .expect_err("bad id")
                .code,
            "invalid_argument"
        );
        assert_eq!(
            subagent_read(&guard, &cache, &dirs, S1, "missing")
                .expect_err("missing")
                .code,
            "not_found"
        );
